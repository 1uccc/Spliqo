const LanguageContext = createContext();

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    try {
      const saved = localStorage.getItem('spliqo_language');
      if (saved === 'en' || saved === 'vi') return saved;
      // Auto-detect browser language
      if (navigator.language && navigator.language.startsWith('en')) {
        return 'en';
      }
    } catch {
      // fallback
    }
    return 'vi';
  });

  const [displayCurrency, setDisplayCurrencyState] = useState(() => {
    try {
      const saved = localStorage.getItem('spliqo_display_currency');
      if (saved) return saved.toUpperCase();
    } catch {
      // fallback
    }
    return 'VND';
  });

  useEffect(() => {
    const langCode = language === 'en' ? 'en' : 'vi';
    document.documentElement.lang = langCode;
    document.title =
      langCode === 'en'
        ? 'Spliqo - Smart Group Expense Splitting'
        : 'Spliqo - Chia Tiền Nhóm Thông Minh';
  }, [language]);

  useEffect(() => {
    if (displayCurrency && displayCurrency !== 'VND') {
      refreshExchangeRates().catch(() => {});
    }
  }, [displayCurrency]);

  const setLanguage = useCallback((lang) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('spliqo_language', lang);
    } catch {
      // fallback
    }
  }, []);

  const setDisplayCurrency = useCallback((currencyCode) => {
    const normalized = (currencyCode || 'VND').toUpperCase();
    setDisplayCurrencyState(normalized);
    try {
      localStorage.setItem('spliqo_display_currency', normalized);
    } catch {
      // fallback
    }
  }, []);

  const t = useCallback(
    (key, defaultText) => {
      const langDict = translations[language] || translations.vi;
      if (langDict && langDict[key]) {
        return langDict[key];
      }
      return defaultText || key;
    },
    [language]
  );

  const formatMoney = useCallback(
    (vndAmount, options = {}) => {
      const targetCurrency = options.currency || displayCurrency;
      return formatDisplayCurrency(vndAmount, targetCurrency, language === 'en');
    },
    [displayCurrency, language]
  );

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        displayCurrency,
        setDisplayCurrency,
        formatMoney,
        t,
        isEn: language === 'en',
        isVi: language === 'vi'
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
