const LanguageContext = createContext();

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    try {
      const saved = localStorage.getItem('spliqo_language');
      if (saved === 'en' || saved === 'vi') return saved;
      // Auto-detect browser language
      if (navigator.language && navigator.language.startsWith('en')) {
        return 'en';
      }
    } catch {
      // fallback
    }
    return 'vi';
  });

  const setLanguage = (lang) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('spliqo_language', lang);
    } catch {
      // fallback
    }
  };

  const t = (key, defaultText) => {
    const langDict = translations[language] || translations.vi;
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    return defaultText || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, isEn: language === 'en', isVi: language === 'vi' }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
